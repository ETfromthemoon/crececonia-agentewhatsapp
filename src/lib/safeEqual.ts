/**
 * Comparación de strings en tiempo constante (evita timing attacks al comparar
 * tokens/secretos). Devuelve false ante longitudes distintas.
 */
export function timingSafeEqual(a: string, b: string): boolean {
  if (a.length !== b.length) return false;
  let mismatch = 0;
  for (let i = 0; i < a.length; i++) {
    mismatch |= a.charCodeAt(i) ^ b.charCodeAt(i);
  }
  return mismatch === 0;
}
